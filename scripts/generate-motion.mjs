import { writeFile } from 'node:fs/promises';
import { spring } from 'motion';

// Short settling tails. Motion runs at build time, never in the client bundle.
const presets = {
  menu: { duration: 380, bounce: 0.18 },
  press: { duration: 240, bounce: 0.22 },
  selection: { duration: 280, bounce: 0.14 },
  popup: { duration: 240, bounce: 0.12 },
};
const fallback = [], curves = [];
for (const [name, options] of Object.entries(presets)) {
  const curve = String(spring({ keyframes: [0, 1], ...options }));
  const duration = curve.split(' ')[0];
  fallback.push(`  --motion-${name}-duration: ${duration};`, `  --motion-${name}: ${duration} cubic-bezier(.2, .8, .2, 1);`);
  curves.push(`    --motion-${name}: ${curve};`);
}
const css = `/* Generated by npm run motion:generate using Motion 14.1.0. */
:root {
${fallback.join('\n')}
}
@supports (transition-timing-function: linear(0, 1)) {
  :root {
${curves.join('\n')}
  }
}
`;
await writeFile(new URL('../src/motion-tokens.css', import.meta.url), css);
console.log('Generated four restrained Motion spring presets.');
