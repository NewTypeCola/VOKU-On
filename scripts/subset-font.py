"""Rebuild lossless web subsets: pip install 'fonttools[woff]==4.60.1'.

Keep the original SUIT/OFL source; the derived internal family is VOKU Archive Sans.
Every source codepoint is retained. CSS downloads only the needed unicode ranges.
"""
from collections import Counter
from hashlib import sha256
from pathlib import Path
import json
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

root = Path(__file__).resolve().parent.parent
source = root / 'public/fonts/suit.woff2'
original = TTFont(source, recalcTimestamp=False)
cmap = original.getBestCmap()
points = set(cmap)
ui = ''.join(p.read_text() for p in (root / 'src').rglob('*') if p.suffix in {'.tsx', '.ts', '.json'})
catalog = json.loads((root / 'public/data/catalog.json').read_text())
frequency = Counter(''.join(row['title'] for row in catalog))
core = ({ord(c) for c in ui} | {ord(c) for c, _ in frequency.most_common(768)} | set(range(0x100))) & points
remaining = sorted(points - core)
groups = [('core', sorted(core))] + [(f'{i // 128 + 1:02}', remaining[i:i+128]) for i in range(0, len(remaining), 128)]
out = root / 'public/fonts/subsets'
out.mkdir(exist_ok=True)
css, report, covered = [], [], set()
for label, chars in groups:
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    options.notdef_outline = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=chars)
    worker.subset(font)
    for item in font['name'].names:
        names = {1: 'VOKU Archive Sans', 4: 'VOKU Archive Sans', 6: 'VOKUArchiveSans', 16: 'VOKU Archive Sans', 21: 'VOKU Archive Sans'}
        if item.nameID in names:
            item.string = names[item.nameID].encode(item.getEncoding())
    target = out / f'voku-sans-{label}.woff2'
    font.save(target)
    digest = sha256(target.read_bytes()).hexdigest()[:10]
    final = target.with_name(f'{target.stem}.{digest}.woff2')
    target.rename(final)
    # Exact cmap coverage, advance widths and decomposed outlines at default weight.
    built = TTFont(final)
    built_cmap = built.getBestCmap()
    assert set(chars) <= set(built_cmap)
    assert not covered.intersection(chars)
    covered.update(chars)
    old_glyphs, new_glyphs = original.getGlyphSet(), built.getGlyphSet()
    for code in chars:
        a, b = old_glyphs[cmap[code]], new_glyphs[built_cmap[code]]
        assert a.width == b.width, hex(code)
        pa, pb = DecomposingRecordingPen(old_glyphs), DecomposingRecordingPen(new_glyphs)
        a.draw(pa); b.draw(pb)
        assert pa.value == pb.value, hex(code)
    if 'fvar' in original:
        assert [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in original['fvar'].axes] == [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in built['fvar'].axes]
        for weight in [100, 400, 700, 900]:
            old_glyphs = original.getGlyphSet(location={'wght': weight})
            new_glyphs = built.getGlyphSet(location={'wght': weight})
            for code in chars[::max(1, len(chars)//24)]:
                pa, pb = DecomposingRecordingPen(old_glyphs), DecomposingRecordingPen(new_glyphs)
                old_glyphs[cmap[code]].draw(pa); new_glyphs[built_cmap[code]].draw(pb)
                assert pa.value == pb.value, (hex(code), weight)
    ranges = []
    start = end = chars[0]
    for code in chars[1:] + [None]:
        if code is not None and code == end + 1:
            end = code
        else:
            ranges.append(f'U+{start:X}' + (f'-{end:X}' if end != start else ''))
            start = end = code
    css.append('@font-face {\n  font-family: SUIT;\n  font-style: normal;\n  font-weight: 100 900;\n  font-display: swap;\n  src: url("/fonts/subsets/' + final.name + '") format("woff2");\n  unicode-range: ' + ','.join(ranges) + ';\n}')
    report.append({'file': final.name, 'bytes': final.stat().st_size, 'characters': len(chars)})
assert covered == points
# Remove only obsolete files generated by this script, never the original font.
current = {item['file'] for item in report}
for old in out.glob('voku-sans-*.woff2'):
    if old.name not in current:
        old.unlink()
(root / 'src/fonts.css').write_text('/* Generated by scripts/subset-font.py. Outlines and weight axes match the original SUIT. */\n'+'\n'.join(css)+'\n')
(out / 'manifest.json').write_text(json.dumps({'sourceSha256': sha256(source.read_bytes()).hexdigest(), 'sourceCharacters': len(points), 'subsets': report},indent=2)+'\n')
index = root / 'index.html'
text = index.read_text()
import re
text = re.sub(r'href="/fonts/(?:suit\.woff2|subsets/voku-sans-core\.[a-f0-9]+\.woff2)"', 'href="/fonts/subsets/'+report[0]['file']+'"',text)
index.write_text(text)
print(json.dumps({'sourceBytes': source.stat().st_size, 'coreBytes': report[0]['bytes'], 'allCharactersPreserved': len(covered), 'files': len(report)},indent=2))
